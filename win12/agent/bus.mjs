/* ==========================================================================
   Разговор поверхностей оболочки

   Рабочий стол и панель задач — две разные поверхности, и живут они в разных
   мирах: каждая со своим кодом и своей памятью. Чтобы панель знала об окнах
   рабочего стола, а щелчок по ней доходил обратно, им нужен общий язык.

   Здесь он самый простой: кто-то говорит, остальные слышат. Сказанное
   складывается по порядку, слушающий помнит, на чём остановился, и ждёт
   продолжения — без опроса каждые полсекунды и без лишней работы.
   ========================================================================== */

const ПАМЯТЬ = 200;            // сколько последних сообщений храним
const ЖДАТЬ = 25000;           // сколько ждать нового, прежде чем ответить пусто

let счёт = 0;
const лента = [];
const ждущие = [];

function разбудить(){
  while (ждущие.length){
    const кто = ждущие.pop();
    clearTimeout(кто.часы);
    кто.ответ(лента.filter(с => с.n > кто.с));
  }
}

export function bus(){
  return {
    /* сказать всем: { тема, что } */
    async 'ui.say'({ тема, что }){
      if (typeof тема !== 'string' || !тема) throw new Error('у сообщения нет темы');
      лента.push({ n:++счёт, тема, что, когда:Date.now() });
      while (лента.length > ПАМЯТЬ) лента.shift();
      разбудить();
      return { n:счёт };
    },

    /* услышать всё, сказанное после числа «с»; ждёт, пока не появится новое */
    async 'ui.hear'({ с = 0, темы }){
      const мимо = т => !Array.isArray(темы) || !темы.length || темы.includes(т);
      const было = лента.filter(м => м.n > с && мимо(м.тема));
      if (было.length) return { n:счёт, список:было };

      return await new Promise(ответ => {
        const кто = { с, ответ:список => ответ({ n:счёт, список:список.filter(м => мимо(м.тема)) }) };
        кто.часы = setTimeout(() => {
          const где = ждущие.indexOf(кто);
          if (где >= 0) ждущие.splice(где, 1);
          ответ({ n:счёт, список:[] });
        }, ЖДАТЬ);
        ждущие.push(кто);
      });
    },

    /* последнее сказанное по теме — чтобы новая поверхность сразу знала, как дела */
    async 'ui.last'({ тема }){
      for (let i = лента.length - 1; i >= 0; i--)
        if (лента[i].тема === тема) return { n:счёт, что:лента[i].что };
      return { n:счёт, что:null };
    }
  };
}
