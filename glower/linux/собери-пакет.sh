#!/bin/bash
# ==========================================================================
#  Пакет GlowerOS: всё наше — одним .deb
#
#  Зачем это вообще. Раньше единственным способом получить новую версию
#  была полная переустановка: записать флешку, загрузиться, поставить
#  систему заново. Между тем меняется в ней почти всегда одно и то же —
#  наши файлы: оболочка, агент, панель, сценарии. Несколько мегабайт.
#
#  Теперь они лежат в обычном пакете, а пакет — в обычном репозитории.
#  Система обновляется так же, как обновляется любая другая: нажатием в
#  «Параметрах», через тот же apt, которым ставятся все прочие программы.
#  Ничего своего для этого писать не пришлось: apt, dpkg и Магазин уже
#  умеют всё, что нужно.
#
#  Пакет собирается из готового корня образа, а не из исходного дерева, —
#  ровно из того, что и уедет человеку. Так список файлов не может
#  разойтись со сборкой: он и есть сборка.
#
#  Имена переменных латиницей: bash кириллических не понимает.
# ==========================================================================
set -eu

ROOTFS=${1:-}
VERSION=${2:-}
OUTDIR=${3:-}

if [ -z "$ROOTFS" ] || [ -z "$VERSION" ] || [ -z "$OUTDIR" ]; then
  echo "как звать: собери-пакет.sh <корень образа> <версия> <куда положить .deb>" >&2
  exit 2
fi

# Версия для dpkg должна начинаться с цифры и не знает букв в начале:
# из «v10.2» делаем «10.2», из «v10.2-3-gabcdef» — «10.2+3.gabcdef».
# Иначе apt не сможет сравнить её с предыдущей и обновление не предложит.
DEB_VER=$(printf '%s' "$VERSION" | sed 's/^v//; s/-/+/; s/-/./g')
case "$DEB_VER" in [0-9]*) ;; *) DEB_VER="0+$DEB_VER" ;; esac

BUILD=$(mktemp -d)
# mktemp делает каталог доступным только хозяину, и корень пакета выходит с
# правами 700: распакованная система получила бы каталог, в который никто,
# кроме root, не войдёт.
chmod 755 "$BUILD"
trap 'rm -rf "$BUILD"' EXIT

# --------------------------------------------------------------------------
# Что кладём в пакет.
#
# Только то, чем никто, кроме нас, не владеет. Чужой файл — например,
# /etc/xdg/foot/foot.ini из пакета foot — положить нельзя: dpkg откажется
# ставить пакет, который лезет на чужую территорию, и обновление встанет.
# Поэтому всё своё живёт в /usr/share/glower, а настройки чужим программам
# мы отдаём отдельным каталогом, не подменяя их файлов.
#
# Каталоги берём целиком: добавленный в них файл попадёт в пакет сам.
# Отдельные имена в /usr/bin перечислены руками — там наши файлы лежат
# вперемешку с системными, и шаблон «всё подряд» унёс бы чужое.
OUR_DIRS="usr/share/glower usr/share/plymouth/themes/glower"
OUR_FILES="usr/bin/glower-session usr/bin/glower-install usr/bin/glower-fix
            usr/bin/glower-shell usr/bin/glower-open-package usr/bin/glower-shot
            usr/bin/glower-tray usr/bin/glower-greeter usr/bin/врач
            usr/bin/vrach usr/bin/dhfx
            usr/share/applications/glower.desktop
            etc/glower-release"

found=0
for d in $OUR_DIRS; do
  [ -d "$ROOTFS/$d" ] || continue
  mkdir -p "$BUILD/$(dirname "$d")"
  cp -a "$ROOTFS/$d" "$BUILD/$d"
  found=1
done
for f in $OUR_FILES; do
  [ -e "$ROOTFS/$f" ] || continue
  mkdir -p "$BUILD/$(dirname "$f")"
  cp -a "$ROOTFS/$f" "$BUILD/$f"
  found=1
done
[ "$found" = 1 ] || { echo "в корне образа не нашлось ни одного нашего файла" >&2; exit 1; }

# Размер пакета apt показывает человеку — считаем честно.
SIZE=$(du -sk "$BUILD" | cut -f1)

mkdir -p "$BUILD/DEBIAN"
cat > "$BUILD/DEBIAN/control" <<CONTROL
Package: glower
Version: $DEB_VER
Section: misc
Priority: optional
Architecture: all
Maintainer: GlowerOS <noreply@glower.local>
Installed-Size: $SIZE
Depends: python3, python3-gi, gir1.2-webkit2-4.1, gir1.2-gtklayershell-0.1, nodejs
Description: GlowerOS — оболочка, агент и сценарии системы
 Всё, что делает из Ubuntu систему GlowerOS: рабочий стол и панель,
 агент, экран входа, установщик, приёмник лотка и вспомогательные
 сценарии. Обновляется обычным путём, вместе со всей системой.
CONTROL

# Ничего после установки пакет не делает — и это сознательно.
#
# Файлы обновились, но в памяти машины живёт прежнее: оболочка уже
# прочитала свои страницы, агент работает старый. Перезапустить их втихую
# значит закрыть человеку всё открытое посреди работы. Поэтому пакет молчит,
# а «Параметры», поставив обновление, скажут словами: новая версия
# заработает после выхода и входа.

mkdir -p "$OUTDIR"
NAME="glower_${DEB_VER}_all.deb"
dpkg-deb --root-owner-group --build "$BUILD" "$OUTDIR/$NAME" >/dev/null
echo "$OUTDIR/$NAME"
