/* ---------- батарея в полосе ----------

   Заряд виден сразу, а не только тому, кто открыл меню: заливка значка
   показывает уровень, рядом с ней появляется молния, когда машина
   заряжается, и подпись говорит словами. Считает всё это стол — он один
   опрашивает машину, а мы показываем. */
Шина.следи('батарея', что => {
  const кнопка = $('#батарея');
  if (!кнопка || !что) return;
  const залив = кнопка.querySelector('.залив');
  const уровень = что['уровень'];

  if (что['есть'] === false || уровень === null || уровень === undefined){
    кнопка.dataset.подсказка = что['сеть'] ? 'Питание от розетки' : 'Батареи нет';
    if (залив) залив.setAttribute('width', '10');
    кнопка.classList.remove('заряжается', 'мало');
    return;
  }

  /* Ширина заливки — от нуля до десяти: столько места внутри корпуса
     значка. Меньше половины точки не рисуем: пустой корпус понятнее, чем
     полоска в один пиксель. */
  if (залив){
    const ш = Math.max(0, Math.min(10, Math.round(уровень / 10)));
    залив.setAttribute('width', String(ш));
  }
  кнопка.classList.toggle('заряжается', !!что['заряжается']);
  кнопка.classList.toggle('мало', уровень <= 15 && !что['заряжается']);
  кнопка.dataset.подсказка = уровень + '% · '
    + (что['заряжается'] ? 'заряжается' : что['сеть'] ? 'от розетки' : 'от батареи');
});

