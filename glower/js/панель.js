/* ==========================================================================
   Панель: полоса наверху и то, что она открывает.

   Отдельная маленькая программа. Про рабочий стол она знает ровно два
   слова: «открой вот это» и «экран сейчас занят мной». Всё остальное берёт
   у агента — часы у себя, значки программ у него.

   Здесь намеренно нет ничего из оболочки: ни окон, ни файловой системы, ни
   приложений. Их отсутствие и есть главная особенность этой страницы —
   то, чего нет, не может нарисоваться внутри полосы в тридцать пикселей.
   ========================================================================== */
'use strict';

const $ = с => document.querySelector(с);

/* ---------- разговор с агентом ---------- */
/* Свой маленький вызов вместо общего Platform: тому нужна половина
   оболочки, а нам — один POST на localhost. */
const Агент = {
  адрес:location.origin,
  async зов(метод, доводы){
    const о = await fetch(this.адрес + '/rpc', {
      method:'POST',
      headers:{ 'Content-Type':'application/json' },
      body:JSON.stringify({ method:метод, params:доводы || {} })
    });
    const д = await о.json();
    if (!д.ok) throw new Error(д.error || 'агент отказал');
    return д.result;
  }
};

/* ---------- общая шина: разговор со столом ---------- */
const Шина = {
  async скажи(тема, что){
    try { await Агент.зов('ui.say', { 'тема':тема, что }); } catch(e){}
  },
  async последнее(тема){
    try { return (await Агент.зов('ui.last', { 'тема':тема }) || {}).что; }
    catch(e){ return null; }
  },
  /* Нынешнее положение дел и место, с которого слушать дальше, — за один
     раз.

     По отдельности выходит гонка, и она уже случилась. Панель спрашивала
     «как дела сейчас», получала «занят», а весть «свободен» приходила в
     зазор между этим вопросом и подпиской — и терялась навсегда. Панель
     оставалась спрятанной, и со стороны это выглядело так, будто её нет
     вовсе.

     Слушать с начала времён тоже нельзя: шина помнит две сотни последних
     сообщений, и подписчик с нуля проигрывает их все подряд. */
  async следи(тема, дело){
    let с = 0;
    try {
      const д = await Агент.зов('ui.last', { 'тема':тема });
      с = (д || {}).n || 0;
      if (д && д.что !== null && д.что !== undefined) дело(д.что);
    } catch(e){}
    this.слушай([тема], м => { if (м.тема === тема) дело(м.что); }, с);
  },

  /* Просьбы — не состояние, и повторять их нельзя.

     «Стол занят» — это как дела сейчас: узнал и живи с этим. «Открой Пуск» —
     однократная просьба, и если применить её при запуске, панель откроет
     меню сама собой, без человека. Поэтому здесь только новое, а прошлое
     пропускаем. */
  async команды(тема, дело){
    let с = 0;
    try { с = (await Агент.зов('ui.last', { 'тема':тема }) || {}).n || 0; }
    catch(e){}
    this.слушай([тема], м => { if (м.тема === тема) дело(м.что); }, с);
  },

  слушай(темы, дело, сНачала){
    let с = сНачала || 0;
    (async () => {
      for (;;){
        try {
          const д = await Агент.зов('ui.hear', { с, темы });
          с = д.n || с;
          (д['список'] || []).forEach(дело);
        } catch(e){ await new Promise(r => setTimeout(r, 3000)); }
      }
    })();
  }
};

/* ---------- разговор с оболочкой-хозяином ---------- */
/* Хозяин держит поверхность панели. Пока ничего не открыто, она ростом в
   полосу; открыли меню — растёт во весь экран, чтобы меню было где
   показать, и забирает клавиатуру, чтобы в поиск можно было напечатать. */
const Хозяин = {
  было:'',
  скажись(){
    const раскрыт = document.body.classList.contains('открыто');
    const весть = { 'раскрыт':раскрыт, 'скрыта':!!this.спрятать,
                    'высота':Math.round(
                      parseFloat(getComputedStyle(document.documentElement)
                        .getPropertyValue('--полоса-высота')) || 30) };
    const строкой = JSON.stringify(весть);
    if (строкой === this.было) return;
    this.было = строкой;
    try { window.webkit.messageHandlers.glowerPanel.postMessage(строкой); }
    catch(e){ /* в браузере хозяина нет — и растягивать нечего */ }
  }
};

/* ---------- меню ---------- */
/* Открытое меню всегда одно: закрываем прежнее, прежде чем открыть новое.
   Иначе два раскрытых меню держат поверхность растянутой по очереди, и
   закрыть её нечем. */
let открытое = null;

function закрой(){
  if (!открытое) return;
  открытое.узел.remove();
  открытое.кнопка.classList.remove('открыта');
  открытое = null;
  document.body.classList.remove('открыто');
  Хозяин.скажись();
}

function открой(кнопка, id, наполни){
  const тоже = открытое && открытое.id === id;
  закрой();
  if (тоже) return;
  const узел = document.createElement('div');
  узел.className = 'окошко';
  узел.id = id;
  document.body.appendChild(узел);
  кнопка.classList.add('открыта');
  открытое = { id, узел, кнопка };
  document.body.classList.add('открыто');
  Хозяин.скажись();
  наполни(узел);
}

$('#навес').onclick = закрой;
addEventListener('keydown', е => { if (е.key === 'Escape') закрой(); });

/* ---------- часы ---------- */
const дни = ['января','февраля','марта','апреля','мая','июня',
             'июля','августа','сентября','октября','ноября','декабря'];
function часы(){
  const т = new Date();
  $('#время').textContent =
    String(т.getHours()).padStart(2, '0') + ':' + String(т.getMinutes()).padStart(2, '0');
  $('#дата').textContent = т.getDate() + ' ' + дни[т.getMonth()];
}
часы();
setInterval(часы, 5000);

/* ---------- лоток чужих программ ---------- */
/* Значки кладут сюда мессенджеры, качалки и VPN. Приёмник живёт отдельной
   службой, мы лишь показываем, что он собрал. */
async function лоток(){
  let было = '';
  const место = $('#лоток');
  for (;;){
    try {
      const д = await Агент.зов('sys.tray');
      const список = д['значки'] || [];
      const строкой = JSON.stringify(список);
      if (строкой !== было){
        было = строкой;
        место.innerHTML = '';
        список.forEach(з => {
          const б = document.createElement('button');
          б.className = 'значок';
          б.title = з.tooltip || з.name || '';
          if (з.iconData){
            const и = document.createElement('img'); и.src = з.iconData; б.appendChild(и);
          } else {
            б.textContent = (з.name || '?').trim().charAt(0).toUpperCase();
          }
          const нажми = действие => Агент.зов('sys.tray.нажать',
            { 'служба':з.service, 'путь':з.path, 'действие':действие }).catch(() => {});
          б.onclick = () => нажми(з.itemIsMenu ? 'ContextMenu' : 'Activate');
          б.oncontextmenu = е => { е.preventDefault(); нажми('ContextMenu'); };
          место.appendChild(б);
        });
      }
    } catch(e){ /* лотка может не быть — это не беда, просто пусто */ }
    await new Promise(r => setTimeout(r, 2000));
  }
}
лоток();

/* ---------- меню программ ---------- */
/* Список программ знает рабочий стол — он же их и открывает. Мы только
   показываем и просим. Держать здесь свой список значило бы держать и весь
   код приложений, а это ровно то, от чего мы уходим. */
$('#программы').onclick = () => открой($('#программы'), 'окно-программ', async узел => {
  узел.innerHTML = '<input class="поиск-программ" id="искать" placeholder="Поиск программ" autocomplete="off">'
                 + '<div class="сетка" id="сетка"></div>';
  const сетка = узел.querySelector('#сетка');
  const поле = узел.querySelector('#искать');
  поле.focus();

  let все = await Шина.последнее('программы') || [];
  if (!все.length){
    Шина.скажи('дай-программы', true);
    await new Promise(r => setTimeout(r, 400));
    все = await Шина.последнее('программы') || [];
  }

  const рисуй = () => {
    const что = поле.value.trim().toLowerCase();
    const виден = все.filter(п => !что || (п.имя || '').toLowerCase().includes(что));
    сетка.innerHTML = '';
    if (!виден.length){
      сетка.innerHTML = '<div class="пусто">Ничего не нашлось</div>';
      return;
    }
    виден.forEach(п => {
      const б = document.createElement('button');
      б.className = 'программа';
      б.innerHTML = '<span class="лицо"></span><span class="имя"></span>';
      const лицо = б.querySelector('.лицо');
      лицо.style.background = п.фон || 'rgba(255,255,255,.12)';
      лицо.textContent = п.знак || '▢';
      б.querySelector('.имя').textContent = п.имя || п.id;
      б.onclick = () => { Шина.скажи('открой', { 'вид':'приложение', id:п.id }); закрой(); };
      сетка.appendChild(б);
    });
  };
  поле.oninput = рисуй;
  рисуй();
});

/* ---------- питание ---------- */
/* Спрашиваем и делаем сами.

   Раньше панель просила об этом стол, и вопрос «точно выключить?» приходил
   оттуда с заметным опозданием: просьба шла через шину, стол её подхватывал
   не сразу, и человек успевал подумать, что нажатие не сработало. Своё
   окошко открывается мгновенно. */
const ДЕЙСТВИЯ = [
  { id:'lock',     имя:'Заблокировать',    вопрос:null },
  { id:'logout',   имя:'Выйти из системы', вопрос:'Все открытые программы закроются.' },
  { id:'sleep',    имя:'Спящий режим',     вопрос:null },
  { id:'restart',  имя:'Перезагрузка',     вопрос:'Машина перезагрузится.' },
  { id:'shutdown', имя:'Выключение',       вопрос:'Машина выключится.', опасно:true }
];

function занавес(надпись){
  const з = document.createElement('div');
  з.className = 'занавес';
  з.textContent = надпись;
  document.body.appendChild(з);
  /* Поверхность к этому мигу уже схлопнута — меню закрылось. Не растянув её
     обратно, мы нарисовали бы занавес внутри полосы в тридцать пикселей:
     узкая чёрная лента наверху вместо погасшего экрана. */
  document.body.classList.add('открыто');
  Хозяин.скажись();
  return з;
}

async function сделайПитание(д){
  закрой();
  if (д.вопрос){
    const ответ = await спроси(д.имя + '?', д.вопрос + ' Это действие затронет всю машину, а не только оболочку.', д.имя);
    if (!ответ) return;
  }
  const з = занавес(д.id === 'restart' ? 'Перезагрузка…'
                  : д.id === 'sleep' ? 'Засыпаю…'
                  : д.id === 'logout' ? 'Выхожу из системы…' : 'Завершение работы…');
  try { await Агент.зов('sys.power', { action:д.id }); }
  catch(е){
    /* Машина отказалась — убираем занавес и говорим почему. Иначе человек
       остаётся перед чёрным экраном работающего компьютера. */
    з.remove();
    спроси('Не вышло: ' + д.имя, String(е.message || е), 'Понятно', true);
  }
}

$('#питание').onclick = () => открой($('#питание'), 'окно-питания', узел => {
  ДЕЙСТВИЯ.forEach(д => {
    const б = document.createElement('button');
    б.className = 'строка' + (д.опасно ? ' опасно' : '');
    б.textContent = д.имя;
    б.onclick = () => сделайПитание(д);
    узел.appendChild(б);
  });
});

/* ---------- вопрос ---------- */
function спроси(заголовок, текст, кнопка, одна){
  return new Promise(ответь => {
    const фон = document.createElement('div');
    фон.className = 'вопрос-фон';
    фон.innerHTML = '<div class="вопрос"><b></b><p></p><div class="вопрос-низ"></div></div>';
    фон.querySelector('b').textContent = заголовок;
    фон.querySelector('p').textContent = текст;
    const низ = фон.querySelector('.вопрос-низ');
    const закончи = что => { фон.remove(); document.body.classList.remove('открыто');
                             Хозяин.скажись(); ответь(что); };
    if (!одна){
      const отмена = document.createElement('button');
      отмена.className = 'строка'; отмена.textContent = 'Отмена';
      отмена.onclick = () => закончи(false);
      низ.appendChild(отмена);
    }
    const да = document.createElement('button');
    да.className = 'строка главная'; да.textContent = кнопка;
    да.onclick = () => закончи(true);
    низ.appendChild(да);
    document.body.appendChild(фон);
    document.body.classList.add('открыто');
    Хозяин.скажись();
    да.focus();
  });
}

/* ---------- часы: месяц целиком ---------- */
const НЕДЕЛЯ = ['пн','вт','ср','чт','пт','сб','вс'];
$('#часы').onclick = () => открой($('#часы'), 'окно-часов', узел => {
  const т = new Date();
  const первый = new Date(т.getFullYear(), т.getMonth(), 1);
  const сдвиг = (первый.getDay() + 6) % 7;
  const дней = new Date(т.getFullYear(), т.getMonth() + 1, 0).getDate();
  let к = '<div class="месяц">' + дни[т.getMonth()] + ' ' + т.getFullYear() + '</div><div class="числа">';
  НЕДЕЛЯ.forEach(д => { к += '<span class="день-недели">' + д + '</span>'; });
  for (let i = 0; i < сдвиг; i++) к += '<span></span>';
  for (let д = 1; д <= дней; д++)
    к += '<span class="число' + (д === т.getDate() ? ' сегодня' : '') + '">' + д + '</span>';
  узел.innerHTML = к + '</div>';
});

/* ---------- звук и яркость ---------- */
async function ползунок(узел, подпись, взять, поставить){
  const строка = document.createElement('div');
  строка.className = 'ползунок';
  строка.innerHTML = '<span class="подпись"></span><input type="range" min="0" max="100"><span class="сколько"></span>';
  строка.querySelector('.подпись').textContent = подпись;
  const вход = строка.querySelector('input');
  const сколько = строка.querySelector('.сколько');
  узел.appendChild(строка);
  let есть = 0;
  try { есть = Math.round(await взять()); } catch(е){ строка.remove(); return; }
  вход.value = есть; сколько.textContent = есть + '%';
  вход.oninput = () => { сколько.textContent = вход.value + '%'; поставить(+вход.value).catch(() => {}); };
}

$('#звук').onclick = () => открой($('#звук'), 'окно-звука', async узел => {
  узел.innerHTML = '';
  await ползунок(узел, 'Громкость',
    async () => (await Агент.зов('sys.volume.get')).громкость ?? (await Агент.зов('sys.volume.get')).value ?? 0,
    з => Агент.зов('sys.volume.set', { 'громкость':з, value:з }));
  await ползунок(узел, 'Яркость',
    async () => (await Агент.зов('sys.brightness.get')).яркость ?? (await Агент.зов('sys.brightness.get')).value ?? 0,
    з => Агент.зов('sys.brightness.set', { 'яркость':з, value:з }));
  if (!узел.children.length)
    узел.innerHTML = '<div class="пусто">Машина не даёт управлять звуком и яркостью</div>';
});

/* ---------- батарея ---------- */
$('#батарея').onclick = () => открой($('#батарея'), 'окно-батареи', async узел => {
  узел.innerHTML = '<div class="пусто">Смотрю…</div>';
  try {
    const б = await Агент.зов('sys.battery');
    if (!б || б.есть === false || б.present === false){
      узел.innerHTML = '<div class="пусто">Батареи нет — питание от сети</div>';
      return;
    }
    const процент = Math.round(б.процент ?? б.percent ?? 0);
    const заряжается = б.заряжается ?? б.charging;
    узел.innerHTML = '<div class="заряд"><b>' + процент + '%</b><span>'
      + (заряжается ? 'заряжается' : 'от батареи') + '</span></div>';
  } catch(е){
    узел.innerHTML = '<div class="пусто">Машина не рассказала о батарее</div>';
  }
});

