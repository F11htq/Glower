/* ==========================================================================
   Панель: полоса наверху и то, что она открывает.

   Отдельная маленькая программа. Про рабочий стол она знает ровно два
   слова: «открой вот это» и «экран сейчас занят мной». Всё остальное берёт
   у агента — часы у себя, значки программ у него.

   Здесь намеренно нет ничего из оболочки: ни окон, ни файловой системы, ни
   приложений. Их отсутствие и есть главная особенность этой страницы —
   то, чего нет, не может нарисоваться внутри полосы в тридцать пикселей.
   ========================================================================== */
'use strict';

const $ = с => document.querySelector(с);

/* ---------- разговор с агентом ---------- */
/* Свой маленький вызов вместо общего Platform: тому нужна половина
   оболочки, а нам — один POST на localhost. */
const Агент = {
  адрес:location.origin,
  async зов(метод, доводы){
    const о = await fetch(this.адрес + '/rpc', {
      method:'POST',
      headers:{ 'Content-Type':'application/json' },
      body:JSON.stringify({ method:метод, params:доводы || {} })
    });
    const д = await о.json();
    if (!д.ok) throw new Error(д.error || 'агент отказал');
    return д.result;
  }
};

/* ---------- как понимать ответы агента ----------

   Имена полей придумывать нельзя — их надо брать у того, кто отвечает.
   Я придумал: читал «громкость», «процент», «заряжается», а агент отвечает
   volume, battery.level, charging. Ни одного из этих полей в ответе не
   было, и панель честно показывала ноль процентов громкости, пустую
   яркость и прочерк вместо заряда. Человек сказал прямо: показатели
   должны быть настоящими. Ровно тем же — придуманным словом вместо
   чужого — была сломана кнопка перезагрузки.

   Разбор собран в одном месте и проверяется на настоящих ответах живой
   машины. */
const Разбор = {
  громкость(о){ return о && typeof о.volume === 'number' ? о.volume : null; },
  яркость(о){ return о && typeof о.value === 'number' ? о.value : null; },
  /* Уровень заряда: число или null, если батареи нет. */
  уровень(о){
    const б = о && о.battery;
    return о && о.present !== false && б && typeof б.level === 'number' ? б.level : null;
  },
  батарея(о){
    const у = this.уровень(о);
    if (у === null) return (о && о.ac && о.ac.online) ? 'от сети' : 'нет батареи';
    return у + '% · ' + (о.charging ? 'заряжается' : 'от батареи');
  }
};
window.Разбор = Разбор;

/* ---------- общая шина: разговор со столом ---------- */
const Шина = {
  async скажи(тема, что){
    try { await Агент.зов('ui.say', { 'тема':тема, что }); } catch(e){}
  },
  async последнее(тема){
    try { return (await Агент.зов('ui.last', { 'тема':тема }) || {}).что; }
    catch(e){ return null; }
  },
  /* Нынешнее положение дел и место, с которого слушать дальше, — за один
     раз.

     По отдельности выходит гонка, и она уже случилась. Панель спрашивала
     «как дела сейчас», получала «занят», а весть «свободен» приходила в
     зазор между этим вопросом и подпиской — и терялась навсегда. Панель
     оставалась спрятанной, и со стороны это выглядело так, будто её нет
     вовсе.

     Слушать с начала времён тоже нельзя: шина помнит две сотни последних
     сообщений, и подписчик с нуля проигрывает их все подряд. */
  async следи(тема, дело){
    let с = 0;
    try {
      const д = await Агент.зов('ui.last', { 'тема':тема });
      с = (д || {}).n || 0;
      if (д && д.что !== null && д.что !== undefined) дело(д.что);
    } catch(e){}
    this.слушай([тема], м => { if (м.тема === тема) дело(м.что); }, с);
  },

  /* Просьбы — не состояние, и повторять их нельзя.

     «Стол занят» — это как дела сейчас: узнал и живи с этим. «Открой Пуск» —
     однократная просьба, и если применить её при запуске, панель откроет
     меню сама собой, без человека. Поэтому здесь только новое, а прошлое
     пропускаем. */
  async команды(тема, дело){
    let с = 0;
    try { с = (await Агент.зов('ui.last', { 'тема':тема }) || {}).n || 0; }
    catch(e){}
    this.слушай([тема], м => { if (м.тема === тема) дело(м.что); }, с);
  },

  /* Одна связь на все темы.
  
     Каждая подписка держала свою и висела в ожидании до двадцати пяти
     секунд, а больше шести связей к одному адресу браузер одновременно не
     открывает. Очередь разбиралась только по истечении чужого срока, и
     просьба доходила через двадцать шесть секунд — столько же, сколько
     длится ожидание. Мерили: ровно двадцать шесть, три раза подряд. */
  _подписки:new Map(),
  _поток:false,

  слушай(темы, дело, сНачала){
    темы.forEach(т => {
      const список = this._подписки.get(т) || [];
      список.push({ дело, с:сНачала || 0 });
      this._подписки.set(т, список);
    });
    this._начниПоток();
  },

  _начниПоток(){
    if (this._поток) return;
    this._поток = true;
    (async () => {
      /* Пауза — чтобы дождаться остальных подписок: иначе первая же откроет
         свою связь, и весь смысл пропадёт. */
      await new Promise(r => setTimeout(r, 150));
      let начало = 0;
      try { начало = ((await Агент.зов('ui.last', { 'тема':'' })) || {}).n || 0; }
      catch(e){}
      this._подписки.forEach(список => список.forEach(п => { if (!п.с) п.с = начало; }));
      for (;;){
        const темы = [...this._подписки.keys()];
        let с = Infinity;
        this._подписки.forEach(список => список.forEach(п => { с = Math.min(с, п.с); }));
        if (!темы.length || с === Infinity){ await new Promise(r => setTimeout(r, 500)); continue; }
        try {
          const д = await Агент.зов('ui.hear', { с, темы });
          (д['список'] || []).forEach(м => {
            (this._подписки.get(м.тема) || []).forEach(п => {
              if (м.n > п.с) п.дело(м);
            });
          });
          const новое = д.n || с;
          this._подписки.forEach(список => список.forEach(п => {
            if (новое > п.с) п.с = новое;
          }));
        } catch(e){ await new Promise(r => setTimeout(r, 3000)); }
      }
    })();
  }
};

/* ---------- разговор с оболочкой-хозяином ---------- */
/* Хозяин держит поверхность панели. Пока ничего не открыто, она ростом в
   полосу; открыли меню — растёт во весь экран, чтобы меню было где
   показать, и забирает клавиатуру, чтобы в поиск можно было напечатать. */
const Хозяин = {
  было:'',
  /* Высота полосы в покое — одно число, но нужно оно в трёх местах: хозяину
     (какой высоты держать поверхность), столу (на сколько опустить
     развёрнутое окно) и нам самим. Считаем его в одном месте. */
  рост(){
    return Math.round(parseFloat(getComputedStyle(document.documentElement)
      .getPropertyValue('--полоса-высота')) || 30);
  },
  скажись(){
    const раскрыт = document.body.classList.contains('открыто');
    const весть = { 'раскрыт':раскрыт, 'скрыта':!!this.спрятать,
                    'высота':this.рост() };
    const строкой = JSON.stringify(весть);
    if (строкой === this.было) return;
    this.было = строкой;
    try { window.webkit.messageHandlers.glowerPanel.postMessage(строкой); }
    catch(e){ /* в браузере хозяина нет — и растягивать нечего */ }
  }
};

/* ---------- меню ---------- */
/* Открытое меню всегда одно: закрываем прежнее, прежде чем открыть новое.
   Иначе два раскрытых меню держат поверхность растянутой по очереди, и
   закрыть её нечем. */
let открытое = null;

function закрой(){
  if (!открытое) return;
  открытое.узел.remove();
  открытое.кнопка.classList.remove('открыта');
  открытое = null;
  document.body.classList.remove('открыто');
  Хозяин.скажись();
}

function открой(кнопка, id, наполни){
  const тоже = открытое && открытое.id === id;
  закрой();
  if (тоже) return;
  const узел = document.createElement('div');
  узел.className = 'окошко';
  узел.id = id;
  document.body.appendChild(узел);
  кнопка.classList.add('открыта');
  открытое = { id, узел, кнопка };
  document.body.classList.add('открыто');
  Хозяин.скажись();
  наполни(узел);
}

$('#навес').onclick = закрой;
addEventListener('keydown', е => { if (е.key === 'Escape') закрой(); });

/* ---------- часы ---------- */
const дни = ['января','февраля','марта','апреля','мая','июня',
             'июля','августа','сентября','октября','ноября','декабря'];
/* Часовой пояс и вид часов — настройка стола, а панель о ней знать не
   может: настройки лежат в его памяти, не в нашей. Человек выбирал другой
   пояс, время на столе менялось, а в панели оставалось прежним — и
   выглядело это так, будто настройка не работает вовсе.
   Теперь стол присылает и то и другое. Пока не прислал — время машины. */
const Пояс = { где:'', ч24:true };
function часы(){
  const т = new Date();
  const кв = { hour:'2-digit', minute:'2-digit', hour12:!Пояс.ч24 };
  const кд = { day:'numeric', month:'long' };
  if (Пояс.где){ кв.timeZone = Пояс.где; кд.timeZone = Пояс.где; }
  try {
    $('#время').textContent = т.toLocaleTimeString('ru-RU', кв);
    $('#дата').textContent = т.toLocaleDateString('ru-RU', кд);
  } catch(e){
    /* Пояс могли прислать несуществующий — показываем время машины, а не
       пустоту: часы в панели важнее нашей правоты. */
    $('#время').textContent =
      String(т.getHours()).padStart(2, '0') + ':' + String(т.getMinutes()).padStart(2, '0');
    $('#дата').textContent = т.getDate() + ' ' + дни[т.getMonth()];
  }
}
часы();
setInterval(часы, 5000);

/* ---------- лоток чужих программ ---------- */
/* Значки кладут сюда мессенджеры, качалки и VPN. Приёмник живёт отдельной
   службой, мы лишь показываем, что он собрал. */
async function лоток(){
  let было = '';
  const место = $('#лоток');
  for (;;){
    try {
      const д = await Агент.зов('sys.tray');
      const список = д['значки'] || [];
      const строкой = JSON.stringify(список);
      if (строкой !== было){
        было = строкой;
        место.innerHTML = '';
        список.forEach(з => {
          const б = document.createElement('button');
          б.className = 'значок';
          б.title = з.tooltip || з.name || '';
          if (з.iconData){
            const и = document.createElement('img'); и.src = з.iconData; б.appendChild(и);
          } else {
            б.textContent = (з.name || '?').trim().charAt(0).toUpperCase();
          }
          const нажми = действие => Агент.зов('sys.tray.нажать',
            { 'служба':з.service, 'путь':з.path, 'действие':действие }).catch(() => {});
          /* Левой — открыть, правой — меню. Как в Windows, и как человек
             ожидает от значка в углу экрана.
             
             Раньше левая кнопка у части программ открывала их собственное
             меню (так они просят в своём описании), а за полным закрытием
             надо было идти в диспетчер задач и искать программу среди
             системных процессов. */
          б.onclick = () => нажми('Activate');
          б.oncontextmenu = е => {
            е.preventDefault();
            менюЗначка(б, з, нажми);
          };
          место.appendChild(б);
        });
      }
    } catch(e){ /* лотка может не быть — это не беда, просто пусто */ }
    await new Promise(r => setTimeout(r, 2000));
  }
}
лоток();

/* Меню значка в лотке — наше, а не программы.
   
   Своё меню программа показывает сама (ContextMenu), но под Wayland это
   выходит у неё не всегда и не там, где надо. Поэтому рисуем своё, а её
   меню оставляем отдельной строкой — для тех программ, у которых оно
   работает. «Закрыть» же есть всегда: это то, ради чего человек сюда и
   приходит. */
function менюЗначка(кнопка, значок, нажми){
  открой(кнопка, 'окно-значка', узел => {
    узел.innerHTML = '';
    const имя = document.createElement('div');
    имя.className = 'меню-верх';
    имя.innerHTML = '<span class="меню-заряд"></span>';
    имя.querySelector('.меню-заряд').textContent = значок.name || значок.tooltip || 'Программа';
    узел.appendChild(имя);

    const пункт = (текст, дело, опасно) => {
      const с = document.createElement('div');
      с.className = 'меню-строка' + (опасно ? ' опасно' : '');
      с.innerHTML = '<span></span>';
      с.querySelector('span').textContent = текст;
      с.onclick = () => { дело(); закрой(); };
      узел.appendChild(с);
    };

    пункт('Открыть', () => нажми('Activate'));
    if (значок.menu || значок.itemIsMenu) пункт('Меню программы', () => нажми('ContextMenu'));
    пункт('Закрыть программу', async () => {
      try { await Агент.зов('sys.tray.закрыть', { 'служба':значок.service }); }
      catch(е){ спроси('Не вышло закрыть', String(е.message || е), 'Понятно', true); }
    }, true);
  });
}

