/* ==========================================================================
   Две поверхности: рабочий стол и панель

   Оболочка долго жила одним окном в самом низу стопки. Место для панели
   держала прозрачная подставка, а рисовал панель тот же нижний слой — и всё,
   что панель показывала, оказывалось под чужими окнами.

   Видно это было так: развёрнутая программа съедала верхнюю полосу целиком,
   вместе с часами, лотком и поиском. А щелчок по лотку доставался программе
   сверху, и со стороны выглядело, будто клики проходят сквозь лоток.

   Настройками это не лечится. Одна поверхность не может быть одновременно и
   под окнами (обои, значки), и над ними (панель, меню) — так устроены слои
   оконного сервера.

   Поэтому поверхностей две. Одна и та же страница открывается дважды и по
   доводу surface= в адресе понимает, кто она. Лишнее каждая прячет.
   ========================================================================== */
'use strict';

const Поверхности = {
  кто:'стол',

  панель(){ return this.кто !== 'стол'; },
  стол(){ return this.кто === 'стол'; },
  разделено(){ return !!this._раздельно; },

  начни(){
    const п = new URLSearchParams(location.search);
    const с = п.get('surface') || 'desktop';
    /* Разделены ли поверхности, по имени не понять: рабочий стол зовётся
       'desktop' и тогда, когда поверхность всего одна. Признак приходит
       отдельно — его ставит glower-shell, который один и знает, поднял ли
       он панель. */
    this._раздельно = п.get('раздельно') === '1' || с.startsWith('панель');
    this.кто = с.startsWith('панель') ? с : 'стол';
    document.body.classList.add(this.панель() ? 'поверхность-панель' : 'поверхность-стол');
    if (this.кто === 'панель-верх') document.body.classList.add('поверхность-верх');
    if (this._раздельно) document.body.classList.add('поверхности-разделены');
    if (this.панель()) this.начниПанель();
    else if (this._раздельно) this.начниСтол();
  },

  /* Оболочка складывается из десятка файлов, и последний из них правит то,
     что объявил первый. Подменять чужое до того, как оно объявлено, — значит
     подменить пустоту, а потом смотреть, почему ничего не сработало.
     Поэтому подмены ставим, когда страница собрана целиком. */
  когдаСобрано(дело){
    if (document.readyState === 'loading')
      document.addEventListener('DOMContentLoaded', дело, { once:true });
    else дело();
  },

  /* ---------- разговор поверхностей ---------- */

  /* Разговор идёт через агента, а связь с ним появляется не сразу: страница
     сперва его ищет и только потом объявляет себя работающей с системой.
     Всё, что спросит об этом раньше времени, получит «нет».

     Здесь на этом уже обожглись. Подписки ставились, когда страница была
     собрана, — а агент к тому мигу ещё не отозвался, и подписка тихо
     отказывалась слушать. Ошибки не было ни одной: панель просто никогда не
     получала ни одной вести, и меню Пуск не открывалось. Поэтому не
     спрашиваем «готов ли он сейчас», а ждём, пока будет готов. */
  дождисьАгента(){
    if (window.Platform && Platform.mode === 'native') return Promise.resolve(true);
    return new Promise(готово => {
      const ждём = setInterval(() => {
        if (window.Platform && Platform.mode === 'native'){
          clearInterval(ждём); готово(true);
        }
      }, 200);
    });
  },

  async скажи(тема, что){
    await this.дождисьАгента();
    return Platform.rpc('ui.say', { 'тема':тема, что }).catch(() => {});
  },

  слушай(темы, дело){
    let с = 0;
    (async () => {
      await this.дождисьАгента();
      for (;;){
        try {
          const д = await Platform.rpc('ui.hear', { с, темы });
          с = д.n || с;
          (д['список'] || []).forEach(дело);
        } catch(e){ await new Promise(r => setTimeout(r, 3000)); }
      }
    })();
  },

  /* ---------- панель ---------- */

  /* Что считается «панель что-то открыла». Пока открыто хоть одно, её
     поверхность растянута во весь экран: иначе открытое обрезалось бы по
     высоте полосы, то есть пропадало бы целиком.

     Здесь только то, что панель показывает сама и что само же закрывается.
     Скрытому элементу тут не место: пока он есть в разметке, поверхность
     останется во весь экран и заберёт себе все щелчки по экрану — а с виду
     панель будет обычной.

     Диалоги в этом списке не для красоты. Кнопка питания живёт в Пуске, то
     есть на панели, и вопрос «точно выключить?» открывается тоже на ней. Без
     этой строки он рисовался внутри полосы: сплющенный вопрос, обрезанные
     кнопки — и вся полоса разом темнела, потому что затемняющая подложка
     диалога ложилась на неё одну. Со стороны это выглядело как разделённый
     надвое экран.

     Меню Пуск здесь не случайно записано через body: оно открывается
     классом на body, а не на себе самом. Ошибиться тут легко и незаметно —
     селектор просто ни с чем не совпадает, поверхность не растёт, и меню,
     нарисованное внутри полосы высотой в панель, обрезается целиком. На
     экране это выглядит так, будто Пуска нет вовсе. Ровно так и было. */
  ОТКРЫТО:['body.start-open', '#cc.on', '#widgets.on', '#taskview.on',
           '#ctx.on', '#spot-overlay.on', '#power-overlay.on',
           '.dlg-ov.on', '.toasts .toast'].join(', '),

  /* Когда панели не должно быть видно вовсе.

     Экран входа, мастер первоначальной настройки и приветствие занимают
     собой весь экран — они не часть рабочего стола, и полосы над ними быть
     не должно. Установочная среда — то же самое: человек пришёл поставить
     систему, а не пользоваться временной.

     Пряталось это раньше только наполовину: панель не рисовала чужое, но
     полосу наверху всё равно держала. */
  СКРЫТЬ:['#setup', '.welcome', '.вход'].join(', '),

  прячемся(){
    if (document.body.classList.contains('setup-env')) return true;
    if (document.querySelector(this.СКРЫТЬ)) return true;
    /* Мастер настройки панель у себя не открывает — но пока его проходят на
       столе, полосы наверху быть не должно. Спрашиваем о том же, о чём
       спрашивает стол: настройка хранится там же, у обеих поверхностей она
       одна на двоих. */
    try { if (window.Setup && Setup.needed && Setup.needed()) return true; }
    catch(e){}
    return false;
  },

  начниПанель(){
    const хозяину = что => {
      try { window.webkit.messageHandlers.glowerPanel.postMessage(JSON.stringify(что)); }
      catch(e){ /* в браузере хозяина нет, и растягивать нечего */ }
    };

    let было = '';
    let былоПрятались = true;
    const скажись = () => {
      const прячемся = this.прячемся();
      былоПрятались = прячемся;
      const раскрыт = !прячемся && !!document.querySelector(this.ОТКРЫТО);
      /* Высоту меряем по самому нижнему краю того, что панель рисует в
         покое. Угадать её нельзя: она зависит от темы, масштаба и отступов,
         а ошибка в любую сторону видна сразу: либо полоса обрезана, либо экран
         теряет место впустую. */
      let низ = 0;
      if (!раскрыт && !прячемся){
        document.querySelectorAll('.topbar > *').forEach(у => {
          const к = у.getBoundingClientRect();
          if (к.height) низ = Math.max(низ, к.bottom);
        });
      }
      const весть = { 'раскрыт':раскрыт, 'скрыта':прячемся };
      if (низ && !прячемся) весть['высота'] = Math.ceil(низ) + 12;
      const строкой = JSON.stringify(весть);
      if (строкой === было) return;
      было = строкой;
      хозяину(весть);
    };

    /* Следим не по часам, а по изменениям: панель меняется редко, и опрос
       каждые сто миллисекунд ради этого — работа впустую на слабой машине. */
    new MutationObserver(скажись).observe(document.body,
      { attributes:true, subtree:true, attributeFilter:['class', 'style'] });
    addEventListener('resize', скажись);
    скажись();
    /* Первые кадры страница ещё раскладывается, и померенная высота успевает
       измениться: меряем ещё раз, когда всё встало. */
    setTimeout(скажись, 300);
    setTimeout(скажись, 1500);

    /* Настройку проходят на столе, и панель об этом сама не узнает: за
       изменениями она следит в своей разметке, а настройка меняется в
       чужой. Пока прячемся — переспрашиваем; как только настройка пройдена,
       панель появится. Это единственный опрос здесь, и он идёт только
       тогда, когда панели и так не видно. */
    setInterval(() => { if (былоПрятались) скажись(); }, 1500);

    if (!this._раздельно) return;
    this.когдаСобрано(() => {
      /* Меню Пуск открывает панель, а не стол: на столе оно оказалось бы под
         чужими окнами — ровно та беда, ради которой поверхности и разделены.
         Кнопка Пуска живёт в доке, у стола; он присылает просьбу. */
      this.слушай(['открой-пуск'], м => {
        if (м.тема === 'открой-пуск' && window.Shell) Shell.toggleStart(м.что !== false);
      });

      /* Окна живут у стола: он под ними, и рисовать их должен он. Панель,
         открывая программу, просит об этом стол.

         Подменяем одно место, а не полтора десятка вызовов: WM.open зовут
         и плитки Пуска, и поиск, и списки — перечислять их по одному значит
         однажды забыть про новый. */
      if (window.WM && WM.open){
        WM.open = (id, довод) => {
          this.скажи('открой', { 'вид':'приложение', id, 'довод':довод || null });
          if (window.Shell) Shell.closePanels();
        };
      }
      if (window.Shell && Shell.launch){
        Shell.launch = id => {
          this.скажи('открой', { 'вид':'окно', id });
          Shell.closePanels();
        };
      }
    });
  },

  /* ---------- рабочий стол ---------- */
  начниСтол(){
    this.когдаСобрано(() => {
      /* Просьбы панели: открыть программу у себя. */
      this.слушай(['открой'], м => {
        const что = м.что;
        if (м.тема !== 'открой' || !что) return;
        if (что['вид'] === 'приложение' && window.WM) WM.open(что.id, что['довод'] || undefined);
        else if (что['вид'] === 'окно' && window.Shell) Shell.launch(что.id, null);
      });

      /* Кнопка Пуска в доке и клавиша Win — у стола, а само меню у панели.
         Стол теперь только просит открыть. */
      if (window.Shell && Shell.toggleStart){
        Shell.toggleStart = v => this.скажи('открой-пуск', v === undefined ? true : v);
      }
    });
  }
};

window.Поверхности = Поверхности;

/* Запускаемся сразу и первыми: классы на body решают, как ляжет вся
   остальная страница, и ставить их после неё — значит показать человеку
   лишнее на один кадр. */
Поверхности.начни();
