/* ==========================================================================
   Две поверхности: рабочий стол и панель задач

   Оболочка долго жила одним окном в самом низу стопки. Место под панель
   держала прозрачная подставка, а рисовал панель тот же нижний слой — и всё,
   что она открывала, оказывалось под чужими окнами. Меню Пуск выезжало и
   пряталось за развёрнутой программой; стоило разложить два окна по
   половинам экрана, как панель исчезала под ними. Это не настраивалось: так
   устроены слои оконного сервера, и одна поверхность не может быть
   одновременно и под окнами (обои, значки), и над ними (панель, меню).

   Поэтому поверхностей две. Одна и та же страница открывается дважды, и по
   доводу surface= в адресе понимает, кто она: рабочий стол внизу или панель
   наверху. Лишнее каждая прячет.

   Говорят они через агента — тем самым «разговором поверхностей», ради
   которого он и был написан. Панель просит открыть программу, стол
   открывает и рассказывает, какие окна у него есть.
   ========================================================================== */
'use strict';

const Поверхности = {
  /* 'стол' или 'панель' */
  кто:'стол',
  панель(){ return this.кто === 'панель'; },
  стол(){ return this.кто === 'стол'; },

  /* Разделение включается только там, где есть настоящий оконный сервер со
     слоями. В браузере и на запасном пути через X поверхность одна — там всё
     остаётся как было, и это правильно: делить нечего. */
  разделено(){ return this.кто === 'панель' || !!this._раздельно; },

  начни(){
    const п = new URLSearchParams(location.search);
    const с = п.get('surface');
    /* Разделены ли поверхности, по имени не понять: рабочий стол зовётся
       'desktop' и тогда, когда поверхность одна. Признак приходит отдельно —
       его ставит glower-shell, который один и знает, поднял ли он панель. */
    this._раздельно = п.get('раздельно') === '1' || с === 'панель';
    this.кто = с === 'панель' ? 'панель' : 'стол';
    document.body.classList.add(this.кто === 'панель' ? 'поверхность-панель' : 'поверхность-стол');
    if (this._раздельно) document.body.classList.add('поверхности-разделены');

    if (this.панель()) this.начниПанель();
    else this.начниСтол();
  },

  /* ---------- разговор ---------- */
  скажи(тема, что){
    if (!window.Platform || Platform.mode !== 'native') return Promise.resolve();
    return Platform.rpc('ui.say', { 'тема':тема, что }).catch(() => {});
  },

  слушай(темы, дело){
    if (!window.Platform || Platform.mode !== 'native') return;
    let с = 0;
    const круг = async () => {
      for (;;){
        try {
          const d = await Platform.rpc('ui.hear', { с, темы });
          с = d.n || с;
          (d['список'] || []).forEach(дело);
        } catch(e){ await new Promise(r => setTimeout(r, 3000)); }
      }
    };
    круг();
  },

  /* ---------- панель ---------- */
  начниПанель(){
    /* Поверхность панели ростом ровно в панель: меню в ней не поместится.
       Просим оконный сервер растянуть её, пока что-то открыто, и вернуть
       обратно, когда закрылось. Иначе Пуск обрезало бы по высоте панели. */
    /* Имя канала — латиницей. Кириллица здесь не работает: имя уходит в
       деталь сигнала GObject на той стороне, а та должна быть обычным
       именем. С кириллическим каналом ничего не создавалось, поверхность не
       раскрывалась, и меню Пуск обрезалось по высоте панели — то есть
       пропадало целиком.

       Дублируем через агента: если прямого канала нет, хозяин спрашивает
       сам. Лишний разговор дешевле, чем невидимый Пуск. */
    const скажиХозяину = что => {
      try { window.webkit.messageHandlers.glowerPanel.postMessage(что); }
      catch(e){ /* в браузере хозяина нет — и растягивать нечего */ }
      this.скажи('панель-раскрыта', что === 'раскрыть');
    };
    let былоОткрыто = false;
    const следи = () => {
      const открыто = !!document.querySelector(
        '#start.on, #cc.on, #widgets.on, #notif.on, #power-overlay.on, #ctx.on, #taskview.on');
      if (открыто !== былоОткрыто){
        былоОткрыто = открыто;
        скажиХозяину(открыто ? 'раскрыть' : 'сжать');
      }
    };
    setInterval(следи, 120);
    следи();

    /* Окна открывает стол: они его, и живут они у него. */
    this.слушай(['окна-стола'], м => {
      if (м.тема === 'окна-стола' && window.Shell && Shell.syncDock)
        Shell.окнаСтола = м.что || [];
      if (window.Shell && Shell.syncDock) Shell.syncDock();
    });
  },

  /* ---------- рабочий стол ---------- */
  начниСтол(){
    if (!this._раздельно) return;
    /* Панель просит открыть программу — открываем у себя. */
    this.слушай(['открой'], м => {
      if (м.тема !== 'открой' || !м.что) return;
      const что = м.что;
      if (что.вид === 'приложение' && window.WM) WM.open(что.id, что.довод || undefined);
      /* Нажали на значок запущенной программы: переключить, а не открыть
         второе окно. Что именно делать — свернуть или достать — решает та же
         Shell.launch, что и всегда: правило одно на обе поверхности. */
      else if (что.вид === 'окно' && window.Shell) Shell.launch(что.id, null);
      else if (что.вид === 'машина' && window.OS && OS.запустиПоЯрлыку) OS.запустиПоЯрлыку(что.id);
    });

    /* Рассказываем панели про свои окна: без этого в ней нечего показывать. */
    const расскажи = () => {
      if (!window.WM) return;
      const список = WM.wins.map(w => ({ id:w.appId, title:w.title || '',
        свёрнуто:!!w.min, активно:WM.top() === w }));
      const строкой = JSON.stringify(список);
      if (строкой === this._прошлое) return;
      this._прошлое = строкой;
      this.скажи('окна-стола', список);
    };
    setInterval(расскажи, 700);
  }
};
window.Поверхности = Поверхности;
