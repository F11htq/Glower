/* ==========================================================================
   Две поверхности: рабочий стол и панель

   Оболочка долго жила одним окном в самом низу стопки. Место для панели
   держала прозрачная подставка, а рисовал панель тот же нижний слой — и всё,
   что панель показывала, оказывалось под чужими окнами.

   Видно это было так: развёрнутая программа съедала верхнюю полосу целиком,
   вместе с часами, лотком и поиском. А щелчок по лотку доставался программе
   сверху, и со стороны выглядело, будто клики проходят сквозь лоток.

   Настройками это не лечится. Одна поверхность не может быть одновременно и
   под окнами (обои, значки), и над ними (панель, меню) — так устроены слои
   оконного сервера.

   Поэтому поверхностей две. Одна и та же страница открывается дважды и по
   доводу surface= в адресе понимает, кто она. Лишнее каждая прячет.
   ========================================================================== */
'use strict';

const Поверхности = {
  кто:'стол',

  панель(){ return this.кто !== 'стол'; },
  стол(){ return this.кто === 'стол'; },
  разделено(){ return !!this._раздельно; },

  начни(){
    const п = new URLSearchParams(location.search);
    const с = п.get('surface') || 'desktop';
    /* Разделены ли поверхности, по имени не понять: рабочий стол зовётся
       'desktop' и тогда, когда поверхность всего одна. Признак приходит
       отдельно — его ставит glower-shell, который один и знает, поднял ли
       он панель. */
    this._раздельно = п.get('раздельно') === '1' || с.startsWith('панель');
    this.кто = с.startsWith('панель') ? с : 'стол';
    document.body.classList.add(this.панель() ? 'поверхность-панель' : 'поверхность-стол');
    if (this.кто === 'панель-верх') document.body.classList.add('поверхность-верх');
    if (this._раздельно) document.body.classList.add('поверхности-разделены');
    /* У панели своя страница со своим кодом — здесь ей делать нечего. */
    if (this.стол() && this._раздельно) this.начниСтол();
  },

  /* Оболочка складывается из десятка файлов, и последний из них правит то,
     что объявил первый. Подменять чужое до того, как оно объявлено, — значит
     подменить пустоту, а потом смотреть, почему ничего не сработало.
     Поэтому подмены ставим, когда страница собрана целиком. */
  когдаСобрано(дело){
    if (document.readyState === 'loading')
      document.addEventListener('DOMContentLoaded', дело, { once:true });
    else дело();
  },

  /* ---------- разговор поверхностей ---------- */

  /* Разговор идёт через агента, а связь с ним появляется не сразу: страница
     сперва его ищет и только потом объявляет себя работающей с системой.
     Всё, что спросит об этом раньше времени, получит «нет».

     Здесь на этом уже обожглись. Подписки ставились, когда страница была
     собрана, — а агент к тому мигу ещё не отозвался, и подписка тихо
     отказывалась слушать. Ошибки не было ни одной: панель просто никогда не
     получала ни одной вести, и меню Пуск не открывалось. Поэтому не
     спрашиваем «готов ли он сейчас», а ждём, пока будет готов. */
  дождисьАгента(){
    if (window.Platform && Platform.mode === 'native') return Promise.resolve(true);
    return new Promise(готово => {
      const ждём = setInterval(() => {
        if (window.Platform && Platform.mode === 'native'){
          clearInterval(ждём); готово(true);
        }
      }, 200);
    });
  },

  async скажи(тема, что){
    await this.дождисьАгента();
    return Platform.rpc('ui.say', { 'тема':тема, что }).catch(() => {});
  },

  слушай(темы, дело, сНачала){
    let с = сНачала || 0;
    (async () => {
      await this.дождисьАгента();
      /* С нынешнего места, а не с начала: шина помнит две сотни последних
         сообщений, и подписчик с нуля проигрывает их все. Для «открой» это
         значит открыть заново всё, что открывали за сеанс.
         Если место передали — оно уже спрошено, второй раз незачем. */
      if (!с){
        try { с = (await Platform.rpc('ui.last', { 'тема':темы[0] }) || {}).n || 0; }
        catch(e){}
      }
      for (;;){
        try {
          const д = await Platform.rpc('ui.hear', { с, темы });
          с = д.n || с;
          (д['список'] || []).forEach(дело);
        } catch(e){ await new Promise(r => setTimeout(r, 3000)); }
      }
    })();
  },

  /* Нынешнее состояние и место, с которого слушать дальше, — за один раз.
     По отдельности выходит гонка: весть, пришедшая в зазор между вопросом
     и подпиской, теряется навсегда. На панели мы это уже проходили. */
  async следи(тема, дело){
    await this.дождисьАгента();
    let с = 0;
    try {
      const д = await Platform.rpc('ui.last', { 'тема':тема });
      с = (д || {}).n || 0;
      if (д && д.что !== null && д.что !== undefined) дело(д.что);
    } catch(e){}
    this.слушай([тема], м => { if (м.тема === тема) дело(м.что); }, с);
  },

  /* ---------- занят ли экран самим столом ---------- */

  /* Заставка запуска, экран входа, мастер настройки и приветствие занимают
     собой весь экран. Панель — отдельная страница и знать о них не может:
     они здесь, у стола. Стол говорит прямо, панель по этому слову прячется
     целиком, вместе с отведённой ей полосой.

     Раньше панель пыталась догадаться сама, по своей разметке, и на этом
     сломалась четырежды: то, чего у неё нет, она не видит. */
  ЗАНЯТО:['#boot:not(.gone)', '#setup', '.welcome', '.вход'].join(', '),

  прячемся(){
    /* Сперва — слово стола. Он один знает наверняка, занят ли экран им
       самим, и говорит об этом прямо.

       Своей разметкой тут не обойтись, и это стоило отдельной поломки.
       Приветственную анимацию панель у себя не запускает — стало быть, в её
       разметке приветствия нет и прятаться ей вроде бы не от чего. А на
       столе оно в это время идёт во весь экран, и полоса честно висела
       поверх него: человек видел верхние панели там, где должно было быть
       только приветствие. Спрашивать себя о том, что происходит у соседа, —
       заведомо неверный способ. */
    if (document.body.classList.contains('setup-env')) return true;
    if (document.querySelector(this.ЗАНЯТО)) return true;
    /* Настройка хранится в одном месте на обе поверхности — её можно
       спросить и у себя, не дожидаясь вести со стола. */
    try { if (window.Setup && Setup.needed && Setup.needed()) return true; }
    catch(e){}
    return false;
  },

  начниСтол(){
    this.когдаСобрано(() => {
      /* Просьбы панели: открыть программу у себя. */
      this.слушай(['открой'], м => {
        const что = м.что;
        if (м.тема !== 'открой' || !что) return;
        if (что['вид'] === 'приложение' && window.WM) WM.open(что.id, что['довод'] || undefined);
        else if (что['вид'] === 'окно' && window.Shell) Shell.launch(что.id, null);
      });

      /* Сколько места наверху занимает полоса — знает только она сама.
         Наша страница лежит под ней во весь экран, и оконный сервер полосе
         её не подчиняет: во весь экран — значит во весь экран, полоса
         просто рисуется сверху. Пока мы об этом не знали, развёрнутая
         программа начиналась от нуля, и её заголовок уходил под полосу.

         Тридцать — не догадка, а то же число, что стоит в полосе по
         умолчанию: с ним окна лежат правильно и до того, как полоса
         успеет представиться. */
      const полоса = сколько => {
        const h = Math.max(0, Math.round(+сколько || 0));
        document.documentElement.style.setProperty('--полоса-сверху', h + 'px');
        /* Говорим вслух, каким местом экрана считаем своим. Проверить это
           иначе можно только глазами по снимку, а «врач» покажет числом. */
        this.скажи('рабочая-область', window.WM ? WM.maxRect() : { top:h });
        /* Развёрнутые окна пересчитываем сразу: иначе правильное место
           достанется только тем, кого развернут после. */
        if (!window.WM) return;
        WM.wins.filter(w => w.maximized).forEach(w => {
          const м = WM.maxRect();
          Object.assign(w.node.style, { left:м.left + 'px', top:м.top + 'px',
            width:м.width + 'px', height:м.height + 'px' });
        });
      };
      полоса(30);
      this.следи('полоса-высота', з => полоса(з));

      /* Снизу у чужих окон мы места не отнимаем.
      
         Оболочка держала для дока полосу в сорок восемь пикселей, и чужое
         развёрнутое окно до низа экрана не доставало — под ним оставалась
         лента обоев, ровно та же, что была у наших окон. Держать её незачем:
         док в этом режиме прячется, стоит открыть что угодно, а когда его
         зовут курсором — он просто рисуется поверх.
      
         Гасим и тех, кто скажет это позже: высоту дока сообщают при каждой
         его перестройке, и одного раза здесь не хватило бы. */
      if (window.Shell){
        Shell.tellPanelHeight = () => {};
        /* Ждём агента: без него просьба уходит в пустоту и не повторяется.
           Один раз на этом уже обожглись — с подписками шины.
           «Забыть» — обязательно: сказанное сравнивается с прошлым, а
           прошлым при запуске значится тот же ноль, и просьба не ушла бы
           никуда. */
        this.дождисьАгента().then(() => {
          if (Shell.полосаЗабыть) Shell.полосаЗабыть();
          if (Shell.скажиПолосу) Shell.скажиПолосу(0);
        });
      }

      /* Док прячется, когда есть открытое окно, и показывается при подводе
         курсора к нижнему краю — как в elementary.

         Смысл тот же, что и у панели наверху: экран принадлежит программе,
         с которой человек работает, а не нашим украшениям. Раньше док висел
         всегда и отъедал полосу внизу у каждого окна.

         Кнопку Пуска из дока мы при этом убрали: меню программ живёт на
         панели, и вторая такая же кнопка внизу только путала. */
      const док = document.querySelector('#dock-wrap');
      const пуск = document.querySelector('#start-btn');
      if (пуск) пуск.remove();
      if (док){
        let укурсора = false;
        const обнови = () => {
          const своё = window.WM && WM.wins
            ? WM.wins.some(w => !w.minimized && w.desk === WM.desk) : false;
          /* Чужие окна считаются наравне со своими. Firefox и терминал —
             настоящие окна оконного сервера, и в WM.wins их нет; признак
             ставит опрос чужих окон. Без него док честно прятался от
             Блокнота и спокойно висел поверх браузера. */
          const чужое = document.body.classList.contains('чужие-окна');
          document.body.classList.toggle('док-прячется', (своё || чужое) && !укурсора);
        };
        addEventListener('mousemove', е => {
          const рядом = е.clientY > innerHeight - 56;
          if (рядом === укурсора) return;
          укурсора = рядом;
          обнови();
        });
        new MutationObserver(обнови).observe(document.querySelector('#windows') || document.body,
          { childList:true, subtree:true, attributes:true, attributeFilter:['class'] });
        setInterval(обнови, 800);
        обнови();
      }

      /* Панель — отдельная маленькая страница: приложений она не знает и
         знать не должна. Список для её меню программ даёт стол, он же их и
         открывает. */
      const списокПрограмм = () => {
        if (typeof APPS === 'undefined') return [];
        return Object.keys(APPS).map(id => {
          const п = APPS[id] || {};
          return { id, 'имя':п.name || id, 'знак':п.glyph || '', 'фон':п.bg || '' };
        }).filter(п => п['имя']).sort((a, b) => a['имя'].localeCompare(b['имя'], 'ru'));
      };
      const расскажиПрограммы = () => this.скажи('программы', списокПрограмм());
      расскажиПрограммы();
      this.слушай(['дай-программы'], м => {
        if (м.тема === 'дай-программы') расскажиПрограммы();
      });

      /* Питание панель не делает сама: спрашивать подтверждение и гасить
         экран умеет стол, и уметь это дважды незачем. */
      this.слушай(['питание'], м => {
        if (м.тема !== 'питание' || !window.Shell || !Shell.power) return;
        Shell.power(м.что);
      });

      /* Часы, звук и раскладка пока показывает стол — переносим их на
         панель по одному, а не всё разом. */
      /* Часы, звук и батарею панель показывает сама — у агента для этого всё
         есть, и ходить за этим на стол незачем. Осталась раскладка: она
         хозяйство стола, он говорит о ней оконному серверу.

         Просить стол показать центр управления было прямой ошибкой: в
         раздельном режиме он сам же их и прячет, и нажатие не делало
         ничего. */
      const скажиРаскладку = () => {
        try {
          const к = window.KB && KB.def && KB.def();
          if (к && к.code) this.скажи('раскладка', к.code);
        } catch(e){}
      };
      this.слушай(['покажи'], м => {
        if (м.тема !== 'покажи' || м.что !== 'раскладка') return;
        if (window.KB && KB.next) KB.next();
        setTimeout(скажиРаскладку, 120);
      });
      скажиРаскладку();

      /* Кнопка Пуска в доке и клавиша Win открывают меню программ панели. */
      if (window.Shell && Shell.toggleStart){
        Shell.toggleStart = v => this.скажи('открой-пуск', v === undefined ? true : v);
      }

      /* Рассказываем панели, когда экран занят нами целиком: заставка,
         приветствие, мастер настройки, вход. Панель по этому слову прячется
         вся, вместе с отведённой ей полосой. */
      let было = null;
      const расскажи = () => {
        const занят = this.прячемся();
        if (занят === было) return;
        было = занят;
        this.скажи('стол-занят', занят);
      };
      new MutationObserver(расскажи).observe(document.body,
        { childList:true, subtree:true, attributes:true, attributeFilter:['class'] });
      расскажи();
      /* Подстраховка на случай, если смена прошла мимо наблюдателя: раз в
         секунду недорого, а застрявшая наверху полоса дорога. */
      setInterval(расскажи, 1000);
    });
  }
};

window.Поверхности = Поверхности;

/* Запускаемся сразу и первыми: классы на body решают, как ляжет вся
   остальная страница, и ставить их после неё — значит показать человеку
   лишнее на один кадр. */
Поверхности.начни();
