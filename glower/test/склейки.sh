#!/bin/sh
# Две проверки для скриптов оболочки, которых не делает ни один разбор.
#
# 1. Комментарий внутри команды, склеенной обратным слешем. Он съедает весь
#    остаток команды: пакеты молча не попадают в образ, а bash -n доволен.
#    Так однажды развалилась целая сборка.
#
# 2. Кириллица в именах переменных. Присваивание вида «имя=значение» с
#    русскими буквами bash не понимает вовсе — он принимает это за команду и
#    ищет её в PATH. Проверка синтаксиса и здесь молчит: bash -n такое
#    пропускает, и ошибка вылезает только при запуске, обычно далеко от того
#    места, где её сделали. Имена функций кириллицей bash, наоборот,
#    принимает — их не трогаем, но dash не принимает и их, поэтому для
#    скриптов на /bin/sh ругаемся и на функции.
#
# Имена внутри латиницей — по той же причине, о которой вся вторая проверка.
# Без имён файлов ищем их сами.
#
# Список приходилось вести руками, и он, конечно, отстал: в нём не было ни
# glower-shot, ни vm-старая-машина.sh. Проверка, которая не проверяет
# половину скриптов, хуже отсутствующей — на неё полагаешься.
#
# Имена здесь латиницей, и это не педантизм: dash не понимает
# кириллических имён вовсе, а я написал их тут по привычке и получил
# «not found» на ровном месте — шестой раз за проект.
#
# Ищем по первой строке: нас интересуют только оболочечные скрипты. В
# glower-shell и glower-tray кириллица в именах законна, это Python, и
# ругаться на них нельзя.
if [ $# -eq 0 ]; then
  root=$(cd "$(dirname "$0")/.." && pwd)
  found=$(find "$root" -type f ! -path '*/.git/*' 2>/dev/null | while read -r one; do
    case "$(head -1 "$one" 2>/dev/null)" in
      '#!/bin/sh'|'#!/bin/bash'|'#!/usr/bin/env sh'|'#!/usr/bin/env bash') echo "$one" ;;
    esac
  done)
  # shellcheck disable=SC2086
  set -- $found
  echo "проверяю скриптов: $#"
fi

bad=0
for f in "$@"; do
  [ -f "$f" ] || continue

  out=$(awk -v file="$f" '
    /\\[ \t]*$/ { cont=1; next }
    cont && /^[ \t]*#/ {
      printf "%s:%d: комментарий внутри склеенной команды — остаток списка пропадёт\n", file, NR
      broken=1
    }
    { cont=0 }
    END { exit broken }
  ' "$f") || bad=1
  [ -n "$out" ] && echo "$out"

  vars=$(grep -nE '^[[:space:]]*[А-Яа-яЁё][А-Яа-яЁё_0-9]*=' "$f")
  # Имя с кириллицей ломает не только присваивание, но и любое обращение
  # к переменной: ${ИМЯ} или $ИМЯ — это «bad substitution» при запуске.
  # Проверка ловила только присваивания, и на этом я попался снова:
  # написал ${GLOWER_РАЗМЕР:-...} и получил «скрипты в порядке».
  # Строки-комментарии пропускаем: в них кириллица законна, и первая же
  # версия этой проверки отругала собственное пояснение.
  uses=$(grep -nE '\$\{?[A-Za-z_0-9]*[А-Яа-яЁё]' "$f" | grep -vE '^[0-9]+:[[:space:]]*#')
  if [ -n "$uses" ]; then
    echo "$f: кириллица в имени переменной при обращении:"
    echo "$uses"
    bad=1
  fi
  if [ -n "$vars" ]; then
    echo "$f: кириллица в имени переменной — bash такое присваивание не выполнит:"
    echo "$vars" | sed 's/^/  /'
    bad=1
  fi

  case "$(head -1 "$f")" in
    */bin/sh)
      funcs=$(grep -nE '^[[:space:]]*[А-Яа-яЁё][А-Яа-яЁё_0-9]*\(\)' "$f")
      if [ -n "$funcs" ]; then
        echo "$f: кириллица в имени функции — dash такого не разберёт:"
        echo "$funcs" | sed 's/^/  /'
        bad=1
      fi ;;
  esac
done
# --------------------------------------------------------------------------
# Настройки загрузчика внутри сборщика образа.
#
# Та же ловушка, но третьим языком. GRUB раскрывает только имена из
# латиницы, цифр и подчёркивания: с кириллическим именем он молча
# подставит пустоту, и ключи ядра просто не доедут — а на вид всё в
# порядке. Проверить это иначе можно лишь одним способом: собрать образ,
# записать флешку и загрузиться.
#
# Ищем в кусках вида «set имя=...» и «$имя» внутри mkiso.sh.
#
# Имя переменной здесь — латиницей, и это не педантизм: первую версию этой
# самой проверки я написал с кириллическим именем и получил «command not
# found» от собственного кода. Девятый раз за проект.
grub=glower/linux/mkiso.sh
[ -f "$grub" ] || grub=linux/mkiso.sh
if [ -f "$grub" ]; then
  grubbad=$(grep -nE '^[[:space:]]*set [A-Za-z_0-9]*[А-Яа-яЁё]|\$\{?[A-Za-z_0-9]*[А-Яа-яЁё][A-Za-z_0-9А-Яа-яЁё]*[[:space:]]*$' "$grub" \
          | grep -vE '^[0-9]+:[[:space:]]*#')
  if [ -n "$grubbad" ]; then
    echo "$grub: кириллица в имени переменной загрузчика — GRUB её не раскроет:"
    echo "$grubbad" | sed 's/^/  /'
    bad=1
  fi
fi

[ "$bad" = 0 ] && echo "скрипты в порядке"
exit "$bad"
