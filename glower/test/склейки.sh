#!/bin/sh
# Ищет комментарии внутри команд, склеенных обратным слешем: такой
# комментарий съедает весь остаток команды, и bash -n этого не видит.
# Имена переменных латиницей — dash и awk кириллицу в именах не принимают.
bad=0
for f in "$@"; do
  awk -v file="$f" '
    /\\[ \t]*$/ { cont=1; next }
    cont && /^[ \t]*#/ {
      printf "%s:%d: комментарий внутри склеенной команды — остаток списка пропадёт\n", file, NR
      broken=1
    }
    { cont=0 }
    END { exit broken }
  ' "$f" || bad=1
done
[ "$bad" = 0 ] && echo "склейки в порядке"
exit "$bad"
