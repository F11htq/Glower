/* ==========================================================================
   Сон: уснула ли машина, и если проснулась сразу — кто её разбудил

   Беда, ради которой это написано: человек жмёт «Спящий режим», экран
   гаснет — и через секунду машина включается обратно. Со стороны кажется,
   что сна в системе нет вовсе. На деле сон есть, а будит машину
   устройство: контроллер USB, сетевая карта, порт PCIe, которым прошивка
   разрешила будить и которые шумят сразу после засыпания. Бывает и
   иначе — устройство отказывается засыпать, и ядро отменяет сон целиком.

   Ядро ведёт об этом счёт, и спрашивать его можно без прав:
   — /sys/power/suspend_stats — сколько раз сон удался и сколько сорвался,
     а при срыве — какое устройство отказало и на каком шаге;
   — /sys/class/wakeup/* — у каждого, кто может будить, свой счётчик
     «сколько раз будил» (wakeup_count). Сравнить до сна и после — и виден
     тот, кто разбудил.
   Сколько машина проспала, видно по двум часам: обычные идут и во сне,
   монотонные (process.hrtime) во сне стоят.

   Виновнику отнимаем право будить (glower-sleep off — то же, что галочка
   «Разрешить этому устройству выводить компьютер из ждущего режима» в
   Windows) и усыпляем машину снова. Кнопку питания, крышку и клавиатуру
   ноутбука не трогаем никогда: ими машину будит человек. Вернуть право —
   Параметры → Система → Питание.
   ========================================================================== */
import { execFile } from 'node:child_process';
import { EventEmitter } from 'node:events';
import { existsSync } from 'node:fs';
import { readFile, readdir, readlink, realpath } from 'node:fs/promises';
import { basename, join } from 'node:path';
import { promisify } from 'node:util';

const run = promisify(execFile);
const sysfs = () => process.env.GLOWER_SYSFS || '/sys';
const КОНФ = () => process.env.GLOWER_WAKE_CONF || '/etc/glower/wake-off';
const ПОМОЩНИК = '/usr/bin/glower-sleep';
/* Проснулась раньше — значит, разбудил не человек: за пятнадцать секунд
   человек не успеет ни отойти, ни вернуться */
export const ПОРОГ = 15;
const ПОПЫТОК = 3;

export const события = new EventEmitter();
const спи = мс => new Promise(r => setTimeout(r, мс));
const прочти = (п) => readFile(п, 'utf8').then(т => т.trim(), () => null);

/* ---------- снимок счётчиков ---------- */
export async function снимок(корень = sysfs()){
  корень = await realpath(корень).catch(() => корень);
  const ст = {};
  for (const к of ['success', 'fail', 'last_failed_dev', 'last_failed_errno', 'last_failed_step'])
    ст[к] = await прочти(join(корень, 'power', 'suspend_stats', к));

  const источники = {};
  for (const и of await readdir(join(корень, 'class', 'wakeup')).catch(() => [])){
    const где = await realpath(join(корень, 'class', 'wakeup', и)).catch(() => null);
    const м = где && где.match(/^(.*)\/wakeup\/wakeup\d+$/);
    if (!м || !м[1].startsWith(корень + '/devices/')) continue;
    const путь = м[1].slice(корень.length);
    // будильники без устройства (alarmtimer, autosleep) запретить нельзя
    if (путь === '/devices/virtual' || путь.startsWith('/devices/virtual/')) continue;
    const ч = async ф => Number(await прочти(join(где, ф))) || 0;
    источники[путь] = { имя:await прочти(join(где, 'name')) || basename(путь),
                        wakeup:await ч('wakeup_count'), event:await ч('event_count') };
  }
  return { ст, источники, irq:await прочти(join(корень, 'power', 'pm_wakeup_irq')),
           стена:Date.now(), ход:Number(process.hrtime.bigint() / 1000000n) };
}

/* Кнопка питания, крышка, кнопка сна, встроенная клавиатура — этим будит
   человек. Часы (RTC) будят по заведённому будильнику — тоже не шум */
const ЧЕЛОВЕК = /PNP0C0C|PNP0C0D|PNP0C0E|LNXPWRBN|LNXSLPBN|PNP0303|i8042|serio/i;
const ЧАСЫ = /PNP0B00|rtc/i;
export const можно_запретить = к => !ЧЕЛОВЕК.test(к.путь + ' ' + к.имя) && !ЧАСЫ.test(к.путь + ' ' + к.имя);

/* ---------- что было между двумя снимками ---------- */
export function разбери(до, после){
  const n = x => Number(x) || 0;
  const спала = Math.max(0, Math.round(((после.стена - до.стена) - (после.ход - до.ход)) / 100) / 10);
  const есть_счёт = до.ст.success !== null && после.ст.success !== null;

  if (есть_счёт && n(после.ст.fail) > n(до.ст.fail))
    return { исход:'отказ', спала,
             отказ:{ устройство:после.ст.last_failed_dev, шаг:после.ст.last_failed_step, код:после.ст.last_failed_errno } };
  const уснула = есть_счёт ? n(после.ст.success) > n(до.ст.success) : спала >= 1;
  if (!уснула) return { исход:'не-было', спала };

  const рост = поле => Object.entries(после.источники)
    .map(([путь, и]) => ({ путь, имя:и.имя, на:и[поле] - (до.источники[путь] ? до.источники[путь][поле] : и[поле]) }))
    .filter(к => к.на > 0);
  let кто = рост('wakeup'), точно = true;
  if (!кто.length){ кто = рост('event'); точно = false; }
  /* Мышь будит через свой контроллер USB — растут оба счётчика. Виноват
     тот, кто глубже: запретить мышь лучше, чем все порты USB разом */
  кто = кто.filter(к => !кто.some(д => д.путь !== к.путь && д.путь.startsWith(к.путь + '/')))
    .sort((а, б) => б.на - а.на || б.путь.length - а.путь.length);

  if (спала >= ПОРОГ) return { исход:'спала', спала, кто:кто[0] || null };
  const шум = кто.filter(можно_запретить);
  if (шум.length) return { исход:'разбудили', спала, виновник:шум[0], точно };
  if (кто.length) return { исход:'человек', спала, кто:кто[0] };
  return { исход:'неизвестно', спала };
}

/* ---------- как назвать устройство человеку ---------- */
export async function опиши(путь, корень = sysfs()){
  const где = join(корень, путь);
  const к = await прочти(join(где, 'class'));
  const продукт = await прочти(join(где, 'product'));
  const имя = basename(путь);
  let вид = 'устройство';
  if (к && /^0x[0-9a-f]{6}$/i.test(к)){
    const класс = к.slice(2, 6).toLowerCase();
    вид = класс === '0c03' ? 'контроллер USB'
        : класс.startsWith('02') ? 'сетевая карта'
        : класс === '0604' ? 'порт PCIe'
        : класс.startsWith('03') ? 'видеокарта'
        : класс.startsWith('04') ? 'звуковая карта'
        : класс === '0c05' ? 'контроллер SMBus' : 'устройство PCI';
  } else if (await прочти(join(где, 'idVendor'))){
    вид = 'устройство USB';
  } else if (/PNP0C0D/i.test(имя)) вид = 'крышка';
  else if (/PNP0C0C|LNXPWRBN/i.test(имя)) вид = 'кнопка питания';
  else if (/PNP0B00/i.test(имя)) вид = 'часы';
  const драйвер = await readlink(join(где, 'driver')).then(basename, () => null);
  const подпись = продукт ? `${вид} «${продукт}»` : вид;
  return { путь, имя, вид, драйвер, подпись:драйвер ? `${подпись} (${драйвер})` : подпись };
}

/* устройство, отказавшееся засыпать: ядро называет его коротким именем */
async function найди_по_имени(имя, корень = sysfs()){
  if (!имя || /[/\0]/.test(имя)) return null;
  for (const шина of await readdir(join(корень, 'bus')).catch(() => [])){
    const п = join(корень, 'bus', шина, 'devices', имя);
    const где = await realpath(п).catch(() => null);
    if (где) return опиши(где.slice((await realpath(корень).catch(() => корень)).length), корень);
  }
  return null;
}

/* ---------- запреты ---------- */
export async function запрещённые(){
  const т = await прочти(КОНФ());
  return (т || '').split('\n').map(с => с.trim()).filter(с => с.startsWith('/devices/'));
}

const ПУТЬ = /^\/devices\/[A-Za-z0-9:._/+-]+$/;
async function помощник(что, путь){
  if (!ПУТЬ.test(путь) || путь.includes('..')) throw new Error('это не устройство: ' + путь);
  if (!existsSync(ПОМОЩНИК)) throw new Error('в системе нет glower-sleep — запрещать будить нечем');
  await run('sudo', ['-n', ПОМОЩНИК, что, путь], { timeout:10000 });
}

/* ---------- слежка за одной попыткой сна ---------- */
let последний = null;
let следим = false;

function слова(р){
  if (р.исход === 'отказ'){
    const кто = р.отказ.описание ? р.отказ.описание.подпись : (р.отказ.устройство || 'одно из устройств');
    return { заголовок:'Машина не уснула',
             текст:`Засыпать отказалось: ${кто}${р.отказ.шаг ? ', шаг «' + р.отказ.шаг + '»' : ''}. Компьютер продолжает работать.` };
  }
  if (р.исход === 'разбудили'){
    const кто = р.виновник.описание ? р.виновник.описание.подпись : р.виновник.имя;
    if (р.исправлено) return { заголовок:'Сон сорвался — уже исправлено',
      текст:`Машину будил ${кто}. Будить её он больше не будет${р.снова ? ' — засыпаю снова' : ''}. Вернуть: Параметры → Система → Питание.` };
    return { заголовок:'Машина проснулась сразу', текст:`Её разбудил ${кто}. ${р.почему || ''}`.trim() };
  }
  if (р.исход === 'неизвестно')
    return { заголовок:'Машина проснулась сразу',
             текст:'Кто её разбудил, ядро не сказало' + (р.irq ? ` (прерывание ${р.irq})` : '') + '. Попробуйте отключить мышь или приёмник USB и усыпить снова.' };
  return null;
}

/* до — снимок перед сном, усыпить — как попросить машину уснуть ещё раз */
export async function следи(до, { усыпить, попытка = 1, можно = true } = {}){
  if (следим && попытка === 1) return;
  следим = true;
  try {
    let р = { исход:'не-было' };
    // Пока машина спит, таймеры стоят: первая же проверка после
    // пробуждения увидит итог. Две минуты — на медленное засыпание
    for (let i = 0; i < 120 && р.исход === 'не-было'; i++){
      await спи(1000);
      р = разбери(до, await снимок());
    }
    if (р.исход === 'не-было') return;
    if (р.исход === 'неизвестно') р.irq = (await снимок()).irq;
    if (р.исход === 'отказ') р.отказ.описание = await найди_по_имени(р.отказ.устройство);
    if (р.исход === 'разбудили'){
      р.виновник.описание = await опиши(р.виновник.путь);
      if (!р.точно) р.почему = 'Уверенности, что это он, нет — запрещать ему будить не стали.';
      else if (!можно) р.почему = 'Управление питанием выключено.';
      else {
        try {
          await помощник('off', р.виновник.путь);
          р.исправлено = true;
        } catch(e){ р.почему = 'Запретить ему будить не вышло: ' + String(e.stderr || e.message || e).trim().split('\n')[0]; }
      }
      р.снова = !!(р.исправлено && усыпить && попытка < ПОПЫТОК);
    }
    р.когда = Date.now();
    р.попытка = попытка;
    const с = слова(р);
    if (с) Object.assign(р, с);
    последний = р;
    if (с) события.emit('итог', р);
    if (р.снова){
      await спи(3000);
      const снова = await снимок();
      await усыпить();
      await следи(снова, { усыпить, попытка:попытка + 1, можно });
    }
  } finally {
    if (попытка === 1) следим = false;
  }
}

export function sleep({ allowPower } = {}){
  return {
    /* Что знает система о сне — для Параметров */
    async 'sys.sleep'(){
      const корень = sysfs();
      const режимы = await прочти(join(корень, 'power', 'state')) || '';
      const mem = await прочти(join(корень, 'power', 'mem_sleep')) || '';
      const запреты = [];
      for (const путь of await запрещённые()) запреты.push(await опиши(путь));
      return {
        можно:/\b(mem|freeze)\b/.test(режимы),
        глубокий:(mem.match(/\[(\w+)\]/) || [])[1] || null,
        запрещены:запреты,
        помощник:existsSync(ПОМОЩНИК),
        управление:!!allowPower,
        последний
      };
    },
    /* Вернуть устройству право будить машину */
    async 'sys.sleep.allow'({ путь }){
      if (!allowPower) throw new Error('управление питанием выключено: запустите агент с ключом --allow-power');
      await помощник('on', String(путь || ''));
      return { ok:true };
    }
  };
}
